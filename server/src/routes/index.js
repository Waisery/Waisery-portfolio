import { Router } from 'express';
import { rateLimit } from 'express-rate-limit';
import { protect, adminOnly } from '../middleware/auth.js';
import { validate } from '../middleware/validate.js';
import * as users from '../controllers/users.js';
import * as projects from '../controllers/projects.js';
import * as blog from '../controllers/blog.js';
import * as contact from '../controllers/contact.js';
const router = Router();
const limit = (max, message) => rateLimit({ windowMs: 15 * 60 * 1000, limit: max, standardHeaders: 'draft-8', legacyHeaders: false, message: { error: { message } } });
const authLimit = limit(40, 'Too many sign-in attempts. Please try again in 15 minutes.');
const contactLimit = limit(10, 'Too many messages. Please try again in 15 minutes.');
const commentLimit = limit(40, 'Too many comments. Please try again in 15 minutes.');
router.post('/users/register', authLimit, validate('register'), users.register);
router.post('/users/login', authLimit, validate('login'), users.login);
router.get('/users/me', protect, users.me);
router.get('/projects', projects.list);
router.get('/projects/:id', projects.detail);
router.post('/projects', protect, adminOnly, validate('project'), projects.create);
router.put('/projects/:id', protect, adminOnly, validate('project'), projects.update);
router.delete('/projects/:id', protect, adminOnly, projects.remove);
router.get('/blog', blog.list);
router.get('/blog/:postId/comments', blog.comments);
router.post('/blog/:postId/comments', protect, commentLimit, validate('comment'), blog.comment);
router.get('/blog/:id', blog.detail);
router.post('/blog', protect, validate('post'), blog.create);
router.put('/blog/:id', protect, validate('post'), blog.update);
router.delete('/blog/:id', protect, blog.remove);
router.post('/contact', contactLimit, validate('contact'), contact.create);
router.get('/messages', protect, adminOnly, contact.list);
router.patch('/messages/:id', protect, adminOnly, validate('read'), contact.update);
export default router;
